/** Подсказки ресурса для формы действия: { поле: текст } без пустых. */
export function actionHints(resourceId: string, action: string): Record<string, string> {
  const all = HINTS[resourceId] ?? {}
  const out: Record<string, string> = {}
  for (const [k, v] of Object.entries(all)) {
    if (!v.trim()) continue
    if (k.startsWith(`${action}.`)) out[k.slice(action.length + 1)] = v.trim()
  }
  return out
}

/** Подсказки стандартных форм (ключи без точки), пустые пропускаются. */
export function propertyHints(resourceId: string): Record<string, string> {
  return Object.fromEntries(
    Object.entries(HINTS[resourceId] ?? {})
      .filter(([k, v]) => (!k.includes('.') || /^(attrs|links)\./.test(k)) && v.trim())
      .map(([k, v]) => [k, v.trim()]),
  )
}
